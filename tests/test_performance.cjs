const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {series,chart,exactPanel,latestPanel,healthPanel}=require('../performance.js');
const dates={'2026-11-26':{settled:3,profit_units:-1},'2026-11-25':{settled:4,profit_units:2},'2026-11-27':{settled:0,profit_units:0}};
assert.deepEqual(series(dates).map(d=>[d.date,d.cumulative]),[['2026-11-25',2],['2026-11-26',1]]);
assert.ok(chart(dates).includes('polyline'));
assert.ok(!chart({}).includes('<svg'));
assert.ok(exactPanel({positive_roi:{settled:0},by_date:{}}).includes('first exact-edge results'));
assert.ok(latestPanel({projection_rows:[{model_version:'v2',stats:{Points:{error:-2}}}]}).includes('v2'));
assert.ok(healthPanel(null).includes('not available'));
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const nav=html.match(/<nav id="nav"[\s\S]*?<\/nav>/)[0];
const primary=nav.split('<details')[0];
assert.deepEqual([...primary.matchAll(/data-tab="([^"]+)"/g)].map(x=>x[1]),['sportsbook','daily','players','accuracy','kenpom']);
for(const id of ['games','teams','projections','imports','odds'])assert.ok(nav.includes('data-tab="'+id+'"'));
for(const match of nav.matchAll(/data-tab="([^"]+)"/g))assert.ok(html.includes('id="'+match[1]+'" class="tab'));
assert.ok(html.includes('id="sportsbook" class="tab active"'));
assert.ok(!html.includes('id="games" class="tab active"'));
assert.ok(!fs.readFileSync(path.join(__dirname,'../daily-tab.js'),'utf8').includes('daily_grading.json'));
console.log('Performance chart, empty state, and navigation regression checks passed');
